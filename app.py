def pick_random():
    """กดปุ่มสุ่ม: ล้างตัวกรอง แล้วเลือกสูตรแบบสุ่ม"""
    st.session_state.query = ""
    st.session_state.category = "ทั้งหมด"
    st.session_state.pick = random.choice(RECIPES)["name"]


def search(query, category):
    q = query.strip().lower()
    return [
        r for r in RECIPES
        if (category == "ทั้งหมด" or r["category"] == category)
        and (q == "" or q in r["name"].lower()
             or any(q in ing.lower() for ing in r["ingredients"]))
    ]


# ---------- หน้าเว็บ ----------
st.set_page_config(page_title="ค้นหาสูตรทำขนม", page_icon="🍰")
st.title("🍰 ค้นหาสูตรทำขนม")

query = st.text_input("ค้นหาชื่อขนมหรือวัตถุดิบ", key="query",
                      placeholder="เช่น บราวนี่ หรือ กะทิ")

col1, col2 = st.columns([3, 2])
categories = ["ทั้งหมด"] + sorted({r["category"] for r in RECIPES})
category = col1.selectbox("หมวด", categories, key="category")
col2.write("")
col2.button("🎲 สุ่มสูตร", on_click=pick_random, use_container_width=True)

results = search(query, category)
st.caption(f"พบ {len(results)} สูตร")

if not results:
    st.warning("ไม่พบสูตรที่ค้นหา ลองพิมพ์ชื่อขนมหรือวัตถุดิบอื่น")
else:
    name = st.selectbox("เลือกสูตร", [r["name"] for r in results], key="pick")
    recipe = next(r for r in results if r["name"] == name)

    st.divider()
    st.header(recipe["name"])
    st.caption(f"หมวด: {recipe['category']}  |  เวลา: {recipe['time']}")

    st.subheader("วัตถุดิบ")
    for ing in recipe["ingredients"]:
        st.markdown(f"- {ing}")

    st.subheader("วิธีทำ")
    for i, step in enumerate(recipe["steps"], 1):
        st.markdown(f"{i}. {step}")